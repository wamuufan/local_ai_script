# PID file path helper (inside the container's home so host can read it)
pid_file() {
    local container="$1" tool="$2"
    echo "${BASE_DIR}/${container}/.run/${tool}.pid"
}

# ------------------------------------------------------------------------------
# COLOUR & LOGGING HELPERS
# ------------------------------------------------------------------------------
if [[ -t 1 ]]; then
    RED=$'\033[0;31m'
    GREEN=$'\033[0;32m'
    YELLOW=$'\033[1;33m'
    CYAN=$'\033[0;36m'
    BOLD=$'\033[1m'
    DIM=$'\033[2m'
    RESET=$'\033[0m'
else
    RED='' GREEN='' YELLOW='' CYAN='' BOLD='' DIM='' RESET=''
fi

log_info()    { printf "${CYAN}[INFO]${RESET}    %s\n"    "$*"; }
log_success() { printf "${GREEN}[SUCCESS]${RESET} %s\n"   "$*"; }
log_warn()    { printf "${YELLOW}[WARN]${RESET}    %s\n"  "$*"; }
log_error()   { printf "${RED}[ERROR]${RESET}   %s\n"     "$*" >&2; }
log_step()    { printf "${BOLD}${CYAN} ──▶${RESET} %s\n"  "$*"; }
log_header()  {
    printf "\n${BOLD}${CYAN}%s${RESET}\n" "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
    printf "${BOLD}  %s${RESET}\n"         "$*"
    printf "${BOLD}${CYAN}%s${RESET}\n\n"  "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
}

die() {
    log_error "$*"
    exit 1
}

# ------------------------------------------------------------------------------
# PREREQUISITE CHECKS
# ------------------------------------------------------------------------------
require_cmd() {
    local cmd="$1"
    command -v "$cmd" &>/dev/null
}

check_container_exists() {
    local name="$1"
    distrobox list --no-color 2>/dev/null | awk '{print $3}' | grep -qx "$name"
}

assert_container_exists() {
    local name="$1"
    check_container_exists "$name" \
        || die "Container '${name}' not found. Create it first: localai.sh container new ${name}"
}


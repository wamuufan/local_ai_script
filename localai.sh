# ── OLLAMA ──────────────────────────────────────────────────────────────────
install_ollama() {
    local container="$1"
    local home_dir="${BASE_DIR}/${container}"

    log_header "Installing Ollama → ${container}"

    log_step "Updating package lists..."
    distrobox enter "${container}" -- bash -c "
        export DEBIAN_FRONTEND=noninteractive
        sudo apt-get update -qq
        sudo apt-get install -y -qq curl ca-certificates
    "

    log_step "Downloading and running official Ollama installer..."
    distrobox enter "${container}" -- bash -c "
        set -e
        if command -v ollama &>/dev/null; then
            echo 'Ollama is already installed, skipping.'
            ollama --version
            exit 0
        fi
        curl -fsSL https://ollama.com/install.sh | sh
    "

    mkdir -p "${home_dir}/.ollama/models"

    log_step "Configuring Ollama data directory..."
    cat > "${home_dir}/.ollama/ollama.env" <<EOF
# Ollama runtime environment — auto-generated by localai.sh
export OLLAMA_HOME="${home_dir}/.ollama"
export OLLAMA_MODELS="${home_dir}/.ollama/models"
export OLLAMA_HOST="0.0.0.0:11434"
EOF

    log_success "Ollama installed successfully in '${container}'."
    log_info    "Data directory : ${home_dir}/.ollama"
    log_info    "Pull a model   : localai.sh shell ${container}  →  ollama pull llama3.2"
}

# ── SERVICE CONTROL HELPERS ──────────────────────────────────────────────────
check_and_clean_pid() {
    local container="$1"
    local pid_f="$2"
    local tool_name="$3"

    if [[ -f "${pid_f}" ]]; then
        local old_pid; old_pid="$(cat "${pid_f}")"
        if distrobox enter "${container}" -- bash -c "kill -0 '${old_pid}'" 2>/dev/null; then
            log_warn "${tool_name} is already running (PID ${old_pid}) in '${container}'."
            return 1
        else
            log_info "Stale PID file found, cleaning up..."
            rm -f "${pid_f}"
        fi
    fi
    return 0
}

stop_service_in_container() {
    local container="$1"
    local tool_name="$2"
    local timeout="${3:-10}"
    local pid_f; pid_f="$(pid_file "${container}" "${tool_name}")"

    if [[ ! -f "${pid_f}" ]]; then
        log_warn "No PID file found for ${tool_name} in '${container}'. Is it running?"
        return 0
    fi

    local pid; pid="$(cat "${pid_f}")"
    log_step "Stopping ${tool_name} (PID ${pid}) in '${container}'..."

    distrobox enter "${container}" -- bash -c "
        if kill -0 '${pid}' 2>/dev/null; then
            kill -TERM '${pid}'
            echo 'Sent SIGTERM to ${tool_name}.'
            for i in \$(seq 1 ${timeout}); do
                kill -0 '${pid}' 2>/dev/null || { echo '${tool_name} stopped gracefully.'; exit 0; }
                sleep 1
            done
            kill -KILL '${pid}' 2>/dev/null && echo 'Forced kill after timeout.'
        else
            echo '${tool_name} process not running.'
        fi
    " || true

    rm -f "${pid_f}"
    log_success "${tool_name} stopped."
}

start_ollama() {
    local container="$1"
    local home_dir="${BASE_DIR}/${container}"
    local pid_f;  pid_f="$(pid_file "${container}" "ollama")"
    local log_f="${home_dir}/.run/ollama.log"

    mkdir -p "${home_dir}/.run"

    check_and_clean_pid "${container}" "${pid_f}" "Ollama" || return 0

    log_step "Starting Ollama in '${container}' (background)..."
    distrobox enter "${container}" -- bash -c "
        source '${home_dir}/.ollama/ollama.env' 2>/dev/null || true
        nohup ollama serve > '${log_f}' 2>&1 &
        echo \$! > '${pid_f}'
        echo \"Ollama started with PID \$(cat '${pid_f}')\"
    "

    sleep 1
    if [[ -f "${pid_f}" ]]; then
        local pid; pid="$(cat "${pid_f}")"
        log_success "Ollama started (PID ${pid}). API: http://localhost:11434"
        log_info    "Logs: ${log_f}"
    else
        log_error "Ollama may not have started. Check logs: ${log_f}"
    fi
}

stop_ollama() {
    stop_service_in_container "$1" "ollama" 10
}

# ── COMFYUI ─────────────────────────────────────────────────────────────────
install_comfyui() {
    local container="$1"
    local home_dir="${BASE_DIR}/${container}"
    local comfy_dir="${home_dir}/comfyui"

    log_header "Installing ComfyUI → ${container}"

    log_step "Installing system dependencies..."
    distrobox enter "${container}" -- bash -c "
        set -e
        export DEBIAN_FRONTEND=noninteractive
        # Add Ubuntu 24.04 (Noble) repository directly to the isolated ubuntu.sources
        cat <<'EOF' | sudo tee -a /etc/apt/sources.list.d/ubuntu.sources > /dev/null

Types: deb
URIs: http://archive.ubuntu.com/ubuntu/
Suites: noble
Components: main universe
Signed-By: /usr/share/keyrings/ubuntu-archive-keyring.gpg
EOF
        
        # Pin python3.12 packages to Noble, and ignore everything else from Noble
        cat <<'EOF' | sudo tee /etc/apt/preferences.d/99-noble-python > /dev/null
Package: *python3.12*
Pin: release n=noble
Pin-Priority: 900

Package: *
Pin: release n=noble
Pin-Priority: -10
EOF


        sudo apt-get update -qq
        sudo apt-get install -y -qq \
            python3.12 python3.12-venv python3.12-dev python3-pip \
            git curl ca-certificates \
            libgl1 libglib2.0-0 libsm6 libxext6 libxrender-dev \
            ffmpeg
    "

    log_step "Cloning ComfyUI repository..."
    distrobox enter "${container}" -- bash -c "
        set -e
        if [[ -d '${comfy_dir}' && -f '${comfy_dir}/main.py' ]]; then
            echo 'ComfyUI already exists, pulling latest changes...'
            git -C '${comfy_dir}' pull --ff-only
        else
            git clone --depth=1 https://github.com/comfyanonymous/ComfyUI.git '${comfy_dir}'
        fi
    "

    log_step "Creating Python virtual environment..."
    distrobox enter "${container}" -- bash -c "
        set -e
        if [[ ! -d '${comfy_dir}/.venv' ]]; then
            python3.12 -m venv '${comfy_dir}/.venv'
        fi
    "

    log_step "Installing Python dependencies (this may take a while)..."
    distrobox enter "${container}" -- bash -c "
        set -e
        source '${comfy_dir}/.venv/bin/activate'
        if command -v nvidia-smi &>/dev/null 2>&1; then
            echo 'NVIDIA GPU detected — installing PyTorch with CUDA support...'
            pip install --upgrade pip
            pip install torch torchvision torchaudio --index-url https://download.pytorch.org/whl/cu124
        else
            echo 'No NVIDIA GPU detected — installing CPU-only PyTorch...'
            pip install --upgrade pip
            pip install torch torchvision torchaudio --index-url https://download.pytorch.org/whl/cpu
        fi
        pip install -r '${comfy_dir}/requirements.txt'
    "

    mkdir -p \
        "${comfy_dir}/models/checkpoints" \
        "${comfy_dir}/models/loras" \
        "${comfy_dir}/models/vae" \
        "${comfy_dir}/models/controlnet" \
        "${comfy_dir}/models/clip" \
        "${comfy_dir}/output" \
        "${comfy_dir}/input" \
        "${comfy_dir}/custom_nodes" \
        "${home_dir}/.run"

    cat > "${home_dir}/.comfyui.env" <<EOF
# ComfyUI runtime environment — auto-generated by localai.sh
export COMFYUI_DIR="${comfy_dir}"
export COMFYUI_VENV="${comfy_dir}/.venv"
export COMFYUI_HOST="0.0.0.0"
export COMFYUI_PORT="8188"
EOF

    log_success "ComfyUI installed successfully in '${container}'."
    log_info    "App directory  : ${comfy_dir}"
    log_info    "Models folder  : ${comfy_dir}/models/checkpoints/"
    log_info    "Web UI         : http://localhost:8188  (after start)"
}

start_comfyui() {
    local container="$1"
    local home_dir="${BASE_DIR}/${container}"
    local pid_f;  pid_f="$(pid_file "${container}" "comfyui")"
    local log_f="${home_dir}/.run/comfyui.log"

    mkdir -p "${home_dir}/.run"

    check_and_clean_pid "${container}" "${pid_f}" "ComfyUI" || return 0

    log_step "Starting ComfyUI in '${container}' (background)..."
    distrobox enter "${container}" -- bash -c "
        set -e
        source '${home_dir}/.comfyui.env' 2>/dev/null || true
        source \"\${COMFYUI_VENV}/bin/activate\"
        nohup python3 \"\${COMFYUI_DIR}/main.py\" \
            --listen \"\${COMFYUI_HOST}\" \
            --port \"\${COMFYUI_PORT}\" \
            > '${log_f}' 2>&1 &
        echo \$! > '${pid_f}'
        echo \"ComfyUI started with PID \$(cat '${pid_f}')\"
    "

    sleep 2
    if [[ -f "${pid_f}" ]]; then
        local pid; pid="$(cat "${pid_f}")"
        log_success "ComfyUI started (PID ${pid}). Web UI: http://localhost:8188"
        log_info    "Logs: ${log_f}"
    else
        log_error "ComfyUI may not have started. Check logs: ${log_f}"
    fi
}

stop_comfyui() {
    stop_service_in_container "$1" "comfyui" 15
}

# ==============================================================================
# ▼▼▼  ADD NEW TOOLS HERE  ▼▼▼
#
# Follow this pattern for each new tool:
#
#   install_<toolname>() { ... }   # idempotent setup inside the container
#   start_<toolname>()   { ... }   # background launch + PID file

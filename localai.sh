# ------------------------------------------------------------------------------
# COMMAND: doctor
# ------------------------------------------------------------------------------
cmd_doctor() {
    log_header "LocalAI System Doctor v${SCRIPT_VERSION}"

    local all_ok=true

    check_dep() {
        local cmd="$1"
        local label="${2:-$cmd}"
        local hint="${3:-}"
        printf "  %-22s " "${label}:"
        if require_cmd "${cmd}"; then
            local ver; ver="$("${cmd}" --version 2>&1 | head -1)" || ver="(version unknown)"
            printf "${GREEN}✓ found${RESET}  ${DIM}%s${RESET}\n" "${ver}"
        else
            printf "${RED}✗ not found${RESET}"
            [[ -n "${hint}" ]] && printf "  ${DIM}→ %s${RESET}" "${hint}"
            printf "\n"
            all_ok=false
        fi
    }

    printf "${BOLD}Core dependencies:${RESET}\n"
    check_dep "podman"    "Podman"          "dnf install podman  /  apt install podman"
    check_dep "distrobox" "Distrobox"       "curl -s https://raw.githubusercontent.com/89luca89/distrobox/main/install | sh"
    check_dep "git"       "Git"             "apt install git"
    check_dep "curl"      "curl"            "apt install curl"

    printf "\n${BOLD}Optional / GPU:${RESET}\n"
    check_dep "nvidia-smi" "nvidia-smi (GPU)"  "Install NVIDIA drivers + Container Toolkit"
    check_dep "nvcc"       "nvcc (CUDA)"        "Install CUDA toolkit"

    printf "\n${BOLD}Base directory:${RESET}\n"
    printf "  %-22s " "~/.local/containers:"
    if [[ -d "${BASE_DIR}" ]]; then
        printf "${GREEN}✓ exists${RESET}  ${DIM}%s${RESET}\n" "${BASE_DIR}"
    else
        printf "${YELLOW}⚠ missing${RESET}  ${DIM}(created automatically on first use)${RESET}\n"
    fi

    printf "\n${BOLD}Distrobox containers:${RESET}\n"
    if require_cmd distrobox; then
        local count
        count="$(distrobox list --no-color 2>/dev/null | awk 'NR>1 && NF>0 {c++} END {print c+0}')"
        printf "  %-22s ${CYAN}%s${RESET}\n" "Total containers:" "${count}"
    else
        printf "  ${DIM}(distrobox not available)${RESET}\n"
    fi

    printf "\n"
    if "${all_ok}"; then
        log_success "All core dependencies satisfied. System is ready."
    else
        log_warn    "Some dependencies are missing. Install them and re-run: localai.sh doctor"
        exit 1
    fi
}

# ------------------------------------------------------------------------------
# HELP / USAGE
# ------------------------------------------------------------------------------
cmd_help() {
    cat <<EOF

${BOLD}${CYAN}localai.sh${RESET} — Local AI Environment Manager ${DIM}v${SCRIPT_VERSION}${RESET}

${BOLD}USAGE${RESET}
  localai.sh <command> [arguments]

${BOLD}COMMANDS${RESET}

  ${CYAN}container new   <name>${RESET}
      Create a new Ubuntu 26.04 Distrobox container with an isolated home
      directory at ~/.local/containers/<name>. NVIDIA passthrough enabled.

  ${CYAN}container list${RESET}
      List all containers and their data-directory status.

  ${CYAN}container rm    <name>${RESET}
      Remove a container (distrobox rm). Data directory is NEVER deleted.

  ${CYAN}install  <container> <tool>${RESET}
      Install a tool inside a container (idempotent / safe to re-run).
      Supported tools: ${SUPPORTED_TOOLS[*]}

  ${CYAN}start    <container> <tool>${RESET}
      Start a tool in the background inside the container.
      Prevents double-start via PID file check.

  ${CYAN}stop     <container> <tool>${RESET}
      Gracefully stop a running tool (SIGTERM → SIGKILL after timeout).

  ${CYAN}shell    <container>${RESET}
      Open an interactive shell inside the specified container.

  ${CYAN}doctor${RESET}
      Check host system for required and optional dependencies.

EOF
}

# ------------------------------------------------------------------------------
# MAIN DISPATCHER
# ------------------------------------------------------------------------------
main() {
    local cmd="${1:-help}"
    shift || true

    case "${cmd}" in
        container)
            local sub="${1:-}"
            shift || true
            case "${sub}" in
                new)    cmd_container_new  "$@" ;;
                list)   cmd_container_list      ;;
                rm)     cmd_container_rm    "$@" ;;
                *)
                    log_error "Unknown container sub-command: '${sub}'"
                    log_info  "Usage: localai.sh container {new|list|rm} [args]"
                    exit 1
                    ;;
            esac
            ;;
        install)  cmd_install  "$@" ;;
        start)    cmd_start    "$@" ;;
        stop)     cmd_stop     "$@" ;;
        shell)    cmd_shell    "$@" ;;
        doctor)   cmd_doctor        ;;
        help|-h|--help) cmd_help    ;;
        *)
            log_error "Unknown command: '${cmd}'"
            cmd_help
            exit 1
            ;;
    esac
}

main "$@"

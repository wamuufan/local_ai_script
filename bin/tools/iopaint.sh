#!/usr/bin/env bash
# ==============================================================================
#  bin/tools/iopaint.sh — IOPaint Tool Module
# ==============================================================================

set -euo pipefail

install_iopaint() {
    local container="$1"
    local home_dir="${BASE_DIR}/${container}"
    local iopaint_dir="${home_dir}/iopaint"
    local models_dir="${iopaint_dir}/models"

    log_header "Installing IOPaint → ${container}"

    local avail_kb
    avail_kb="$(df -Pk "${home_dir}" 2>/dev/null | awk 'END {print $4}')" || avail_kb=0
    if (( avail_kb > 0 && avail_kb < 5242880 )); then
        log_warn "Low disk space detected (<5 GB free on ${home_dir}). IOPaint and models require sufficient disk space."
    fi

    steps_begin 4

    log_step "Installing system dependencies..."
    ensure_base_packages "${container}" \
        git curl ca-certificates \
        zstd lz4 pigz tar gzip unzip xz-utils \
        libgl1 libglib2.0-0 libsm6 libxext6 libxrender-dev \
        ffmpeg procps pciutils jq libzstd-dev \
        libtcmalloc-minimal4

    log_step "Installing Miniforge and creating Python 3.10 environment..."
    distrobox enter "${container}" -- bash -c "
        set -e
        ${CONTAINER_HELPERS}
        mkdir -p '${iopaint_dir}'
        rm -rf '${iopaint_dir}/.venv'
        install_miniforge '${iopaint_dir}/conda' '${home_dir}/.cache'
        ensure_conda_env '${iopaint_dir}/conda' 'iopaint' '3.10'
    "

    log_step "Installing Python dependencies (PyTorch & IOPaint)..."
    distrobox enter "${container}" -- bash -c "
        set -e
        ${CONTAINER_HELPERS}
        source '${iopaint_dir}/conda/bin/activate' iopaint
        export PIP_CACHE_DIR='${home_dir}/.cache/pip'
        export PIP_PROGRESS_BAR=on
        mkdir -p \"\${PIP_CACHE_DIR}\"

        pip install --upgrade pip setuptools wheel

        echo 'Installing PyTorch...'
        pip_install_torch torch torchvision

        echo 'Installing IOPaint package...'
        pip install iopaint
    "

    mkdir -p "${models_dir}" "${home_dir}/.run"

    local default_device="cpu"
    if container_has_gpu "${container}"; then
        default_device="cuda"
    fi

    cat > "${home_dir}/.iopaint.env" <<EOF
# IOPaint runtime environment — auto-generated by localai.sh
export IOPAINT_DIR="${iopaint_dir}"
export IOPAINT_CONDA="${iopaint_dir}/conda"
export IOPAINT_ENV_NAME="iopaint"
export IOPAINT_MODEL_DIR="${models_dir}"
export IOPAINT_DEFAULT_DEVICE="${default_device}"
EOF

    log_step "Verifying IOPaint installation..."
    if ! distrobox enter "${container}" -- bash -c "source '${iopaint_dir}/conda/bin/activate' iopaint && command -v iopaint &>/dev/null"; then
        die "IOPaint verification failed. Installation may be incomplete."
    fi
    steps_end

    log_success "IOPaint installed successfully in '${container}'."
    log_info    "App directory  : ${iopaint_dir}"
    log_info    "Models folder  : ${models_dir}"
    log_info    "Web UI         : http://localhost:8082  (after start)"
}

is_installed_iopaint() {
    local h="${BASE_DIR}/$1"
    [[ -d "${h}/iopaint" || -d "${h}/.iopaint" ]]
}

update_iopaint() {
    local container="$1"
    local iopaint_dir="${BASE_DIR}/${container}/iopaint"

    log_header "Updating IOPaint → ${container}"
    steps_begin 1
    log_step "Updating IOPaint package via pip..."
    distrobox enter "${container}" -- bash -c "
        set -e
        source '${iopaint_dir}/conda/bin/activate' iopaint
        export PIP_PROGRESS_BAR=on
        pip install --upgrade iopaint
    "
    steps_end
    if [[ "$(get_tool_status_in_container "${container}" iopaint)" == running* ]]; then
        log_warn "IOPaint is running. Apply with: localai.sh restart ${container}:iopaint"
    fi
    log_success "IOPaint updated in '${container}'."
}

start_iopaint() {
    local container="$1"
    local home_dir="${BASE_DIR}/${container}"
    local pid_f; pid_f="$(pid_file "${container}" "iopaint")"
    local log_f="${LOG_DIR}/${container}/iopaint.log"

    local user_env="${home_dir}/.iopaint.user.env"
    local active_conf
    if active_conf="$(resolve_config_file "${container}")"; then
        extract_tool_config "${active_conf}" "iopaint" > "${user_env}"
        if [[ -s "${user_env}" ]]; then
            log_info "Loaded configuration options from $(basename "${active_conf}") [iopaint]."
        fi
    else
        > "${user_env}"
        log_debug "No active configuration file found (.disabled ignored). Using defaults for iopaint."
    fi

    local target_port="8082"
    if [[ -f "${user_env}" ]]; then
        local env_port
        env_port="$(awk -F'=' '/^[ \t]*export[ \t]+IOPAINT_PORT=/ {gsub(/"/, "", $2); print $2}' "${user_env}" | tail -n 1)"
        if [[ -n "${env_port}" && "${env_port}" =~ ^[0-9]+$ ]]; then
            target_port="${env_port}"
        fi
    fi

    local default_device="cpu"
    if container_has_gpu "${container}"; then
        default_device="cuda"
    fi

    local target_device="${default_device}"
    if [[ -f "${user_env}" ]]; then
        local env_dev
        env_dev="$(awk -F'=' '/^[ \t]*export[ \t]+IOPAINT_DEVICE=/ {gsub(/"/, "", $2); print $2}' "${user_env}" | tail -n 1)"
        if [[ -n "${env_dev}" ]]; then
            target_device="${env_dev}"
        fi
    fi
    if [[ -n "${IOPAINT_DEVICE:-}" ]]; then
        target_device="${IOPAINT_DEVICE}"
        echo "export IOPAINT_DEVICE=\"${target_device}\"" >> "${user_env}"
    fi

    log_info "Compute device target: ${target_device}"

    local start_script="
        set -e
        source '${home_dir}/.iopaint.env' 2>/dev/null || true
        source '${home_dir}/.iopaint.user.env' 2>/dev/null || true
        source \"\${IOPAINT_CONDA}/bin/activate\" \"\${IOPAINT_ENV_NAME:-iopaint}\"
        nohup iopaint start \
            --host \"\${IOPAINT_HOST:-0.0.0.0}\" \
            --port \"\${IOPAINT_PORT:-${target_port}}\" \
            --model \"\${IOPAINT_MODEL:-lama}\" \
            --model-dir \"\${IOPAINT_MODEL_DIR:-\${IOPAINT_DIR}/models}\" \
            --device \"\${IOPAINT_DEVICE:-${target_device}}\" \
            \${IOPAINT_EXTRA_ARGS:-} \
            >> '${log_f}' 2>&1 &
        echo \"\$!\" > '${pid_f}'
    "

    start_service_in_container "${container}" "iopaint" "${target_port}" "python|iopaint" "${start_script}" 30 "http://localhost:${target_port}"
}

stop_iopaint() {
    stop_service_in_container "$1" "iopaint" 15
}

uninstall_iopaint() {
    local container="$1"
    local home_dir="${BASE_DIR}/${container}"

    log_header "Uninstalling IOPaint ← ${container}"
    stop_iopaint "${container}" || true

    steps_begin 1
    log_step "Removing IOPaint application directory and virtualenv..."
    run_with_spinner "Removing IOPaint files" rm -rf "${home_dir}/iopaint" "${home_dir}/.iopaint.env" "${home_dir}/.iopaint.user.env"
    steps_end

    log_success "IOPaint uninstalled from '${container}'."
}

#!/usr/bin/env bash
# ==============================================================================
#  bin/tools/openwebui.sh — Open WebUI Tool Module
# ==============================================================================

set -euo pipefail

install_openwebui() {
    local container="$1"
    local home_dir="${BASE_DIR}/${container}"
    local webui_dir="${home_dir}/.openwebui"

    log_header "Installing Open WebUI → ${container}"

    log_step "Installing system dependencies..."
    distrobox enter "${container}" -- bash -c "
        set -e
        export DEBIAN_FRONTEND=noninteractive
        sudo apt-get update -qq
        sudo apt-get install -y -qq \
            git curl ca-certificates procps pciutils jq
    "

    log_step "Installing Miniforge and creating Python 3.11 environment..."
    distrobox enter "${container}" -- bash -c "
        set -e
        mkdir -p '${webui_dir}'
        if [[ ! -d '${webui_dir}/conda' ]]; then
            curl -fsSL https://github.com/conda-forge/miniforge/releases/latest/download/Miniforge3-Linux-x86_64.sh -o '${webui_dir}/miniforge.sh'
            bash '${webui_dir}/miniforge.sh' -b -u -p '${webui_dir}/conda'
            rm -f '${webui_dir}/miniforge.sh'
        fi
        '${webui_dir}/conda/bin/conda' create -y -n openwebui python=3.11
    "

    log_step "Installing Open WebUI via pip (this may take a few minutes)..."
    distrobox enter "${container}" -- bash -c "
        set -e
        source '${webui_dir}/conda/bin/activate' openwebui
        export PIP_CACHE_DIR='${home_dir}/.cache/pip'
        mkdir -p \"\${PIP_CACHE_DIR}\"
        pip install --upgrade pip setuptools wheel
        pip install open-webui
    "

    mkdir -p "${webui_dir}/data" "${home_dir}/.run"

    cat > "${home_dir}/.openwebui.env" <<EOF
# Open WebUI runtime environment — auto-generated by localai.sh
export WEBUI_DIR="${webui_dir}"
export DATA_DIR="${webui_dir}/data"
EOF

    log_step "Verifying Open WebUI installation..."
    if ! distrobox enter "${container}" -- bash -c "source '${webui_dir}/conda/bin/activate' openwebui && command -v open-webui &>/dev/null"; then
        die "Open WebUI verification failed. Installation may be incomplete."
    fi

    log_success "Open WebUI installed successfully in '${container}'."
    log_info    "App directory  : ${webui_dir}"
    log_info    "Data folder    : ${webui_dir}/data"
    log_info    "Web UI         : http://localhost:8080  (after start)"
}

start_openwebui() {
    local container="$1"
    local home_dir="${BASE_DIR}/${container}"
    local pid_f;  pid_f="$(pid_file "${container}" "openwebui")"
    local log_f="${LOG_DIR}/${container}/openwebui.log"

    mkdir -p "${home_dir}/.run" "${LOG_DIR}/${container}"

    if [[ -f "${log_f}" ]]; then
        local size; size="$(stat -c%s "${log_f}" 2>/dev/null || echo 0)"
        if (( size >= 10485760 )); then
            mv "${log_f}" "${log_f}.old" 2>/dev/null || true
        fi
    fi

    check_and_clean_pid "${container}" "${pid_f}" "Open WebUI" "python\|open-webui" || return 0

    # Extract configuration from localai.conf
    local user_env="${home_dir}/.openwebui.user.env"
    extract_tool_config "${SCRIPT_DIR}/localai.conf" "openwebui" > "${user_env}"
    if [[ -s "${user_env}" ]]; then
        log_info "Loaded configuration options from localai.conf [openwebui]."
    fi

    local port="8080"
    if [[ -f "${user_env}" ]]; then
        port="$(grep -E '^export PORT=' "${user_env}" | cut -d'"' -f2 || echo "8080")"
    fi

    if (echo > "/dev/tcp/127.0.0.1/${port}") 2>/dev/null; then
        log_error "Port ${port} is already open/responding on host!"
        log_info  "Open WebUI or another service appears to be running on http://localhost:${port}."
        return 1
    fi

    log_step "Starting Open WebUI in '${container}' (background)..."
    if ! distrobox enter "${container}" -- bash -c "
        set -e
        source '${home_dir}/.openwebui.env' 2>/dev/null || true
        source '${home_dir}/.openwebui.user.env' 2>/dev/null || true
        source \"\${WEBUI_DIR}/conda/bin/activate\" openwebui
        nohup open-webui serve >> '${log_f}' 2>&1 &
        pid=\$!
        success=false
        for i in \$(seq 1 5); do
            if kill -0 \"\$pid\" 2>/dev/null; then
                sleep 1
                if kill -0 \"\$pid\" 2>/dev/null; then
                    echo \"\$pid\" > '${pid_f}'
                    echo \"Open WebUI started with PID \$pid\"
                    success=true
                    break
                fi
            fi
            sleep 1
        done
        if [[ \"\$success\" != \"true\" ]]; then
            echo \"Open WebUI failed to start. Check logs: ${log_f}\" >&2
            exit 1
        fi
    "; then
        log_error "Open WebUI failed to start or stopped immediately. Check logs: ${log_f}"
        rm -f "${pid_f}"
        return 1
    fi

    if [[ -f "${pid_f}" ]]; then
        local pid; pid="$(cat "${pid_f}" 2>/dev/null || echo "")"
        if [[ -n "${pid}" ]]; then
            wait_for_service "http://localhost:${port}" 20 "Open WebUI" || true
            log_success "Open WebUI started (PID ${pid}). Web UI: http://localhost:${port}"
            log_info    "Logs: ${log_f}"
            return 0
        fi
    fi

    log_error "Open WebUI failed to start or stopped immediately. Check logs: ${log_f}"
    rm -f "${pid_f}"
    return 1
}

stop_openwebui() {
    stop_service_in_container "$1" "openwebui" 15
}

uninstall_openwebui() {
    local container="$1"
    local home_dir="${BASE_DIR}/${container}"

    log_header "Uninstalling Open WebUI ← ${container}"
    stop_openwebui "${container}" || true

    log_step "Removing Open WebUI application directory and virtualenv..."
    rm -rf "${home_dir}/.openwebui" "${home_dir}/.openwebui.env" "${home_dir}/.openwebui.user.env"

    log_success "Open WebUI uninstalled from '${container}'."
}

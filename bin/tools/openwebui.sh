#!/usr/bin/env bash
# ==============================================================================
#  bin/tools/openwebui.sh — Open WebUI Tool Module
# ==============================================================================

set -euo pipefail

# Helper function to install or update Open WebUI and its dependencies,
# resolving pyarrow binary wheel requirements cleanly on Python 3.14+.
_openwebui_pip_install() {
    local container="$1"
    local home_dir="${BASE_DIR}/${container}"
    local webui_dir="${home_dir}/.openwebui"

    distrobox enter "${container}" -- bash -c "
        set -e
        ${CONTAINER_HELPERS}
        export LOCALAI_IGNORE_REQUIRES_PYTHON='${LOCALAI_IGNORE_REQUIRES_PYTHON:-0}'
        source '${webui_dir}/.venv/bin/activate'
        export PIP_CACHE_DIR='${home_dir}/.cache/pip'
        export PIP_PROGRESS_BAR=on
        mkdir -p \"\${PIP_CACHE_DIR}\"
        pip install --upgrade pip setuptools wheel
        echo '     [1/2] Fetching Open WebUI package metadata...'
        pip install --ignore-requires-python --no-deps --upgrade open-webui
        echo '     [2/2] Resolving and installing Open WebUI dependencies (Python 3.14 compatible)...'
        python3 -c '
import glob, importlib.metadata, os, re, site, subprocess, sys

for sp in site.getsitepackages():
    for md in glob.glob(os.path.join(sp, \"open_webui-*.dist-info\", \"METADATA\")):
        with open(md, \"r\", encoding=\"utf-8\") as f:
            txt = f.read()
        txt_new = re.sub(r\"(?m)^(Requires-Dist:\\s*pyarrow)==[^\\s;]+\", r\"\\1>=20.0.0\", txt)
        if txt_new != txt:
            with open(md, \"w\", encoding=\"utf-8\") as f:
                f.write(txt_new)

reqs = []
for r in (importlib.metadata.requires(\"open-webui\") or []):
    if \"extra ==\" in r:
        continue
    r = re.sub(r\"^pyarrow==[^\\s;]+\", \"pyarrow>=20.0.0\", r)
    reqs.append(r)

reqs.append(\"audioop-lts\")
cmd = [sys.executable, \"-m\", \"pip\", \"install\", \"--ignore-requires-python\"] + reqs
subprocess.check_call(cmd)
'
    "
}

install_openwebui() {
    local container="$1"
    local home_dir="${BASE_DIR}/${container}"
    local webui_dir="${home_dir}/.openwebui"

    log_header "Installing Open WebUI → ${container}"

    steps_begin 4

    log_step "Installing system dependencies..."
    ensure_base_packages "${container}" \
        git curl ca-certificates procps pciutils jq ffmpeg \
        python3 python3-venv python3-dev python3-pip build-essential

    log_step "Creating Python virtual environment..."
    distrobox enter "${container}" -- bash -c "
        set -e
        ${CONTAINER_HELPERS}
        mkdir -p '${webui_dir}'
        rm -rf '${webui_dir}/conda'
        ensure_python_venv '${webui_dir}/.venv'
    "

    log_step "Installing Open WebUI via pip (this may take a few minutes)..."
    _openwebui_pip_install "${container}"

    mkdir -p "${webui_dir}/data" "${home_dir}/.run"

    cat > "${home_dir}/.openwebui.env" <<EOF
# Open WebUI runtime environment — auto-generated by localai.sh
export WEBUI_DIR="${webui_dir}"
export WEBUI_VENV="${webui_dir}/.venv"
export DATA_DIR="${webui_dir}/data"
EOF

    log_step "Verifying Open WebUI installation..."
    if ! distrobox enter "${container}" -- bash -c "source '${webui_dir}/.venv/bin/activate' && command -v open-webui &>/dev/null"; then
        die "Open WebUI verification failed. Installation may be incomplete."
    fi
    steps_end

    log_success "Open WebUI installed successfully in '${container}'."
    log_info    "App directory  : ${webui_dir}"
    log_info    "Data folder    : ${webui_dir}/data"
    log_info    "Web UI         : http://localhost:8080  (after start)"
}

is_installed_openwebui() { [[ -d "${BASE_DIR}/$1/.openwebui" || -d "${BASE_DIR}/$1/open-webui" ]]; }

update_openwebui() {
    local container="$1"
    local home_dir="${BASE_DIR}/${container}"
    local webui_dir="${home_dir}/.openwebui"
    log_header "Updating Open WebUI → ${container}"
    steps_begin 1
    log_step "Updating Open WebUI via pip..."
    _openwebui_pip_install "${container}"
    steps_end
    if [[ "$(get_tool_status_in_container "${container}" openwebui)" == running* ]]; then
        log_warn "Open WebUI is running. Apply with: localai.sh restart ${container}:openwebui"
    fi
    log_success "Open WebUI updated in '${container}'."
}

start_openwebui() {
    local container="$1"
    local home_dir="${BASE_DIR}/${container}"
    local pid_f; pid_f="$(pid_file "${container}" "openwebui")"
    local log_f="${LOG_DIR}/${container}/openwebui.log"

    # Extract configuration from localai.conf
    local user_env="${home_dir}/.openwebui.user.env"
    local active_conf
    if active_conf="$(resolve_config_file "${container}")"; then
        extract_tool_config "${active_conf}" "openwebui" > "${user_env}"
        if [[ -s "${user_env}" ]]; then
            log_info "Loaded configuration options from $(basename "${active_conf}") [openwebui]."
        fi
    else
        extract_tool_config "" "openwebui" > "${user_env}"
        log_debug "No active configuration file found. Using built-in aggressive_release fallback for openwebui."
    fi

    local port="8080"
    if [[ -f "${user_env}" ]]; then
        port="$(grep -E '^export PORT=' "${user_env}" | cut -d'"' -f2 || echo "8080")"
    fi

    local start_script="
        set -e
        source '${home_dir}/.openwebui.env' 2>/dev/null || true
        source '${home_dir}/.openwebui.user.env' 2>/dev/null || true
        if [[ -f \"\${WEBUI_DIR}/.venv/bin/activate\" ]]; then
            source \"\${WEBUI_DIR}/.venv/bin/activate\"
        fi
        nohup open-webui serve >> '${log_f}' 2>&1 &
        echo \"\$!\" > '${pid_f}'
    "

    start_service_in_container "${container}" "openwebui" "${port}" "python\|open-webui" "${start_script}" 60 "http://localhost:${port}"
}

stop_openwebui() {
    stop_service_in_container "$1" "openwebui" 15
}

uninstall_openwebui() {
    local container="$1"
    local home_dir="${BASE_DIR}/${container}"

    log_header "Uninstalling Open WebUI ← ${container}"
    stop_openwebui "${container}" || true

    steps_begin 1
    log_step "Removing Open WebUI application directory and virtualenv..."
    run_with_spinner "Removing Open WebUI files" rm -rf "${home_dir}/.openwebui" "${home_dir}/.openwebui.env" "${home_dir}/.openwebui.user.env"
    steps_end

    log_success "Open WebUI uninstalled from '${container}'."
}
